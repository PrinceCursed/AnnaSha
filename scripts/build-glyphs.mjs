// Converts the handwritten lines (Marck Script) and the favicon monogram (Oswald)
// into SVG path data, so the signatures can be drawn with stroke-dashoffset.
// Output: src/glyphs.gen.ts, public/favicon.svg
import fs from 'node:fs';
import opentype from 'opentype.js';

const fsrc = (pkg, file) => `node_modules/@fontsource/${pkg}/files/${file}`;
const load = p => opentype.parse(fs.readFileSync(p).buffer.slice(0));

const marck = [load(fsrc('marck-script', 'marck-script-cyrillic-400-normal.woff')), load(fsrc('marck-script', 'marck-script-latin-400-normal.woff'))];

function glyphFor(fonts, ch) {
  for (const f of fonts) {
    const g = f.charToGlyph(ch);
    if (g && g.index !== 0) return { f, g };
  }
  throw new Error('No glyph for ' + ch);
}

// Lays out lines the same way the browser does for a block with the given
// line-height and padding (all in em), returns path + layout box in units.
function layout(fonts, lines, { lineHeight, padX, padBottom }) {
  const base = fonts[0];
  const upm = base.unitsPerEm;
  const asc = base.tables.hhea.ascender, desc = base.tables.hhea.descender;
  const L = lineHeight * upm;
  const halfLeading = (L - (asc - desc)) / 2;
  const px = padX * upm;
  let d = '', maxW = 0;
  lines.forEach((text, i) => {
    let x = px;
    const y = i * L + halfLeading + asc;
    let prev = null;
    for (const ch of text) {
      const { f, g } = glyphFor(fonts, ch);
      if (prev && prev.f === f) x += f.getKerningValue(prev.g, g);
      d += g.getPath(x, y, upm).toPathData(1);
      x += g.advanceWidth;
      prev = { f, g };
    }
    maxW = Math.max(maxW, x - px);
  });
  const w = Math.round(maxW + 2 * px), h = Math.round(lines.length * L + padBottom * upm);
  return { d, w, h, upm, lineHeight };
}

const sig = {
  name: layout(marck, ['Анна Шапошникова'], { lineHeight: 1.15, padX: 0.15, padBottom: 0.05 }),
  greeting: layout(marck, ['Буду рада', 'знакомству'], { lineHeight: 1.1, padX: 0.15, padBottom: 0.1 }),
};

const out = `// Generated by scripts/build-glyphs.mjs — do not edit.
export type Glyphs = { d: string; w: number; h: number; upm: number };
${Object.entries(sig).map(([k, v]) => `export const ${k}Glyphs: Glyphs = ${JSON.stringify({ d: v.d, w: v.w, h: v.h, upm: v.upm })};`).join('\n')}
`;
fs.writeFileSync('src/glyphs.gen.ts', out);

// Favicon: the «АШ» monogram from the design's thumbnail.
const oswald = load(fsrc('oswald', 'oswald-cyrillic-700-normal.woff'));
const p = oswald.getPath('АШ', 0, 0, 34);
const bb = p.getBoundingBox();
const dx = 50 - (bb.x1 + bb.x2) / 2, dy = 62;
const mono = oswald.getPath('АШ', dx, dy, 34).toPathData(2);
fs.writeFileSync('public/favicon.svg', `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100"><rect width="100" height="100" fill="#5E0B1C"/><path fill="#FAF7F4" d="${mono}"/></svg>\n`);
console.log('glyphs ok', Object.fromEntries(Object.entries(sig).map(([k, v]) => [k, [v.w / v.upm, v.h / v.upm]])));
