// Builds web-ready media from the design export (originals never ship):
//   photos → AVIF + WebP at several widths, video → H.264 mp4 + WebP poster,
//   favicon PNGs. Writes the size manifest to src/media.gen.ts.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import sharp from 'sharp';

const SRC = 'design/export/img';
const OUT = 'public/media';
fs.mkdirSync(OUT, { recursive: true });

const sets = {
  portrait: [480, 720, 854],
  about: [480, 720, 853],
};
const photoWidths = [360, 540, 720, 1080, 1440];

const manifest = {};
const names = fs.readdirSync(SRC).filter(f => f.endsWith('.jpg')).map(f => f.replace('.jpg', ''));
for (const name of names) {
  const src = path.join(SRC, name + '.jpg');
  const meta = await sharp(src).metadata();
  const widths = (sets[name] || photoWidths).filter(w => w <= meta.width);
  for (const w of widths) {
    const img = sharp(src).rotate().resize({ width: w });
    const avif = path.join(OUT, `${name}-${w}.avif`), webp = path.join(OUT, `${name}-${w}.webp`);
    if (!fs.existsSync(avif)) await img.clone().avif({ quality: 50, effort: 6 }).toFile(avif);
    if (!fs.existsSync(webp)) await img.clone().webp({ quality: 78 }).toFile(webp);
  }
  manifest[name] = { w: meta.width, h: meta.height, widths };
  console.log(name, widths.join(','));
}

// Video: H.264, ≤1080p, faststart; poster from the first frame.
const video = path.join(OUT, 'katyassswan.mp4');
if (!fs.existsSync(video)) {
  execFileSync('ffmpeg', ['-y', '-v', 'error', '-i', path.join(SRC, 'katyassswan.mp4'),
    '-vf', "scale='min(1080,iw)':-2", '-c:v', 'libx264', '-profile:v', 'high', '-preset', 'slow', '-crf', '20',
    '-pix_fmt', 'yuv420p', '-c:a', 'aac', '-b:a', '128k', '-movflags', '+faststart', video]);
}
const frame = path.join(OUT, '_frame.png');
execFileSync('ffmpeg', ['-y', '-v', 'error', '-i', video, '-frames:v', '1', frame]);
await sharp(frame).resize({ width: 540 }).webp({ quality: 70 }).toFile(path.join(OUT, 'katyassswan-poster.webp'));
fs.rmSync(frame);
const hasAudio = execFileSync('ffprobe', ['-v', 'error', '-select_streams', 'a', '-show_entries', 'stream=index', '-of', 'csv=p=0', video]).toString().trim() !== '';

// Favicons from the generated SVG.
await sharp('public/favicon.svg').resize(180, 180).png().toFile('public/apple-touch-icon.png');
await sharp('public/favicon.svg').resize(32, 32).png().toFile('public/favicon-32.png');

fs.writeFileSync('src/media.gen.ts', `// Generated by scripts/optimize-media.mjs — do not edit.
export const images = ${JSON.stringify(manifest, null, 2)} as const;
export type ImageName = keyof typeof images;
export const video = { src: 'media/katyassswan.mp4', poster: 'media/katyassswan-poster.webp', hasAudio: ${hasAudio} };
`);
console.log('video', (fs.statSync(video).size / 1e6).toFixed(1) + ' MB', 'audio:', hasAudio);
